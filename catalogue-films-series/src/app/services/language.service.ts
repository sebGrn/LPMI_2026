@Injectable({ providedIn: 'root' })
export class LanguageService {
  readonly language = signal<Language>('fr');

  /** Définit la langue initiale de l’application dans le document HTML. */
  constructor() {
    this.updateDocumentLanguage('fr');
  }

  /** Applique une langue prise en charge et met à jour la direction du document. */
  setLanguage(language: string): void {
    const supportedLanguages: readonly string[] = ['fr', 'en', 'es', 'zh', 'hi', 'ar', 'bn', 'pt', 'id', 'ur', 'ru', 'de', 'it', 'pl', 'uk'];
    if (supportedLanguages.includes(language)) {
      const selectedLanguage = language as Language;
      this.language.set(selectedLanguage);
      this.updateDocumentLanguage(selectedLanguage);
    }
  }

  /** Met à jour les attributs de langue et de sens de lecture de la page. */
  private updateDocumentLanguage(language: Language): void {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' || language === 'ur' ? 'rtl' : 'ltr';
  }

  /** Renvoie la traduction d’une clé dans la langue sélectionnée. */
  t(key: TranslationKey): string {
    const language = this.language();
    if (language === 'fr' || language === 'en' || language === 'es') return translations[language][key];
    return additionalTranslations[language][key];
  }

  /** Traduit un genre si une traduction est disponible. */
  genre(value: string): string {
    const language = this.language();
    const existingTranslation = genreTranslations[value]?.[language];
    if (existingTranslation) return existingTranslation;
    if (language === 'fr' || language === 'en' || language === 'es') return value;
    return additionalGenreTranslations[language][value] ?? value;
  }

  /** Traduit le type du média, par exemple film ou série. */
  mediaType(value: string): string {
    if (value === 'Film') return this.t('film');
    if (value === 'Série') return this.t('series');
    return value;
  }
}
